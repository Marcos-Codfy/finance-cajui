/// As ilustrações leves do Cerrado, para os estados vazios.
///
/// São a versão calma do ícone-herói: chapadas, sem volume, sobre um disco
/// do fundo afundado, e pintadas só com os tokens de cor do tema — o mesmo
/// desenho vale no claro e no escuro. Cada vazio escolhe a que conversa com
/// ele, para as telas não repetirem o mesmo desenho.
enum CajuiCerrado {
  /// O cajuí com a castanha e uma folha no pé: o fruto da marca, para o que
  /// ainda não começou.
  cashew,

  /// A folha larga do cerrado, com as nervuras: o que ainda vai crescer.
  leaf,

  /// O galho de ipê-amarelo em flor: o vazio que é boa notícia, como não
  /// ter dívida nenhuma.
  ipe,
}
